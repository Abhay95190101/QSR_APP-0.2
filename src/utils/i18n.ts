/**
 * Gets localized text for an item based on the selected language
 */
export function getLocalizedItem(item: MenuItem, lang: LanguageCode) {
  if (lang === 'en' || !item.translations || !item.translations[lang]) {
    return {
      name: item.name,
      description: item.description,
      dietary: item.dietary,
    };
  }
  const t = item.translations[lang]!;
  return {
    name: t.name || item.name,
    description: t.description || item.description,
    dietary: t.dietary || item.dietary,
  };
}

export function getLocalizedCategory(category: string, lang: LanguageCode): string {
  if (lang === 'en') return category;
  const match = CATEGORY_TRANSLATIONS[category];
  if (match && match[lang]) {
    return match[lang]!;
  }
  return category;
}
